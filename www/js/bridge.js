// Capacitor çekirdek JS'i paketlenmediği için (derleme adımı yok) yerel eklentiye,
// Android köprüsünün sunduğu nativePromise/addListener ile doğrudan ulaşılır.
// Tarayıcıda (köprü yok) null döner.
export function nativePlugin(name, win = globalThis.window) {
  const C = win && win.Capacitor;
  if (!C || typeof C.isNativePlatform !== 'function' || !C.isNativePlatform() || typeof C.nativePromise !== 'function') return null;
  const call = (method) => (opts) => C.nativePromise(name, method, opts || {});
  return {
    addListener: async (event, cb) => C.addListener(name, event, cb),
    play: call('play'),
    openExternal: call('openExternal'),
    enterPip: call('enterPip'),
    pause: call('pause'),
    resume: call('resume'),
    stop: call('stop'),
    seekTo: call('seekTo'),
    setResizeMode: call('setResizeMode'),
    setImmersive: call('setImmersive'),
    getInsets: call('getInsets'),
    isTv: call('isTv'),
    setTvMode: call('setTvMode'),
    multiPlay: call('multiPlay'),
    multiRect: call('multiRect'),
    multiFit: call('multiFit'),
    multiMute: call('multiMute'),
    multiStop: call('multiStop'),
    multiStopAll: call('multiStopAll'),
    setRect: call('setRect'),
    clearRect: call('clearRect'),
    getTracks: call('getTracks'),
    getLevels: call('getLevels'),
    setBrightness: call('setBrightness'),
    setVolume: call('setVolume'),
    selectTrack: call('selectTrack'),
    download: call('download'),
    probe: call('probe'),
    getStats: call('getStats'),
    planSync: call('planSync'),
    planStatus: call('planStatus'),
    planPermissions: call('planPermissions'),
    planLaunch: call('planLaunch'),
    downloadApk: call('downloadApk'),
    installApk: call('installApk'),
    deleteFile: call('deleteFile'),
    saveText: call('saveText'),
    shareText: call('shareText'),
    recordStart: call('recordStart'),
    recordStop: call('recordStop'),
    recordList: call('recordList'),
    recordDelete: call('recordDelete'),
    dlStart: call('dlStart'),
    dlList: call('dlList'),
    dlPause: call('dlPause'),
    dlPauseAll: call('dlPauseAll'),
    dlResume: call('dlResume'),
    dlResumeAll: call('dlResumeAll'),
    dlRemove: call('dlRemove'),
    setAudioDelay: call('setAudioDelay'),
    setNightMode: call('setNightMode'),
    setDecoder: call('setDecoder'),
    setSubtitleStyle: call('setSubtitleStyle'),
    tvSyncWatchNext: call('tvSyncWatchNext'),
    voiceSearch: call('voiceSearch'),
    castSyncReply: call('castSyncReply'),
    castStart: call('castStart'),
    castStop: call('castStop'),
    castInfo: call('castInfo'),
    castPairOpen: call('castPairOpen'),
    castPairClose: call('castPairClose'),
    castUnpair: call('castUnpair'),
    castNow: call('castNow'),
    castExt: call('castExt'),
    castDiscover: call('castDiscover'),
    castRequest: call('castRequest'),
  };
}
